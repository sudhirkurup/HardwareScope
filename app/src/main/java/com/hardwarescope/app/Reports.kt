import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

data class SRow(val cat: String, val name: String, val value: String)

data class Snapshot(val device: String, val time: Long, val rows: List<SRow>) {
    val label: String get() = "$device · " + SimpleDateFormat("MMM d, HH:mm", Locale.US).format(Date(time))
}

/** Export, import and comparison of hardware reports. */
object Reports {
    private val stamp get() = SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US).format(Date())

    fun baseName(device: String) = "HardwareScope_" + device.replace(Regex("[^A-Za-z0-9]+"), "-").trim('-') + "_" + stamp

    // ---------- JSON snapshot (used for compare and for importing another phone's data)

    fun toJson(s: Snapshot): String {
        val arr = JSONArray()
        s.rows.forEach { arr.put(JSONObject().put("c", it.cat).put("n", it.name).put("v", it.value)) }
        return JSONObject()
            .put("app", "HardwareScope").put("format", 1)
            .put("device", s.device).put("time", s.time)
            .put("android", Build.VERSION.RELEASE)
            .put("rows", arr).toString(1)
    }

    fun fromJson(text: String): Snapshot {
        val o = JSONObject(text)
        require(o.optString("app") == "HardwareScope") { "Not a HardwareScope snapshot" }
        val arr = o.getJSONArray("rows")
        val rows = (0 until arr.length()).map {
            val r = arr.getJSONObject(it); SRow(r.getString("c"), r.getString("n"), r.getString("v"))
        }
        return Snapshot(o.getString("device"), o.getLong("time"), rows)
    }

    // ---------- Tabular exports

    private fun csvCell(s: String) = if (s.any { it == ',' || it == '"' || it == '\n' }) "\"" + s.replace("\"", "\"\"") + "\"" else s

    fun csv(s: Snapshot): String = buildString {
        append('﻿') // BOM so Excel opens UTF-8 correctly
        append("Category,Item,Value\r\n")
        append("Report,Device,${csvCell(s.device)}\r\n")
        append("Report,Generated,${SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US).format(Date(s.time))}\r\n")
        s.rows.forEach { append(csvCell(it.cat)).append(',').append(csvCell(it.name)).append(',').append(csvCell(it.value)).append("\r\n") }
    }

    private fun esc(s: String) = s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")

    fun html(s: Snapshot): String = buildString {
        append("<!doctype html><html><head><meta charset='utf-8'><meta name='viewport' content='width=device-width,initial-scale=1'>")
        append("<title>HardwareScope – ${esc(s.device)}</title><style>")
        append("body{font-family:system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:#0e1116;color:#e6eaf2;margin:0;padding:20px}")
        append("h1{font-size:22px;margin:0 0 4px}p.m{color:#8a94a6;margin:0 0 20px}h2{font-size:15px;color:#3ddc97;margin:24px 0 6px}")
        append("table{border-collapse:collapse;width:100%;max-width:960px}td{padding:6px 10px;border-bottom:1px solid #2a3140;vertical-align:top;font-size:13px}")
        append("td:first-child{color:#8a94a6;width:38%}@media print{body{background:#fff;color:#000}td:first-child{color:#444}h2{color:#0a7}}")
        append("</style></head><body><h1>${esc(s.device)}</h1><p class='m'>Hardware report · ")
        append(SimpleDateFormat("yyyy-MM-dd HH:mm", Locale.US).format(Date(s.time))).append(" · generated by HardwareScope</p>")
        s.rows.groupBy { it.cat }.forEach { (cat, rows) ->
            append("<h2>${esc(cat)}</h2><table>")
            rows.forEach { append("<tr><td>${esc(it.name)}</td><td>${esc(it.value)}</td></tr>") }
            append("</table>")
        }
        append("</body></html>")
    }

    // ---------- Comparison

    data class Diff(val cat: String, val name: String, val a: String, val b: String, val delta: String, val different: Boolean)

    private val numRe = Regex("^\\s*(-?[0-9]+(?:\\.[0-9]+)?)\\s*(.*)$")

    fun compare(a: Snapshot, b: Snapshot): List<Diff> {
        val keyA = LinkedHashMap<String, SRow>()
        a.rows.forEach { keyA.putIfAbsent(it.cat + "\u0000" + it.name, it) }
        val keyB = LinkedHashMap<String, SRow>()
        b.rows.forEach { keyB.putIfAbsent(it.cat + "\u0000" + it.name, it) }
        val keys = LinkedHashSet<String>().apply { addAll(keyA.keys); addAll(keyB.keys) }
        return keys.map { k ->
            val ra = keyA[k]; val rb = keyB[k]
            val va = ra?.value ?: "—"; val vb = rb?.value ?: "—"
            var delta = ""
            val ma = numRe.find(va); val mb = numRe.find(vb)
            if (ma != null && mb != null && ma.groupValues[2].take(4) == mb.groupValues[2].take(4)) {
                val x = ma.groupValues[1].toDouble(); val y = mb.groupValues[1].toDouble()
                if (x != 0.0 && x != y) delta = f("%+.0f%%", (y - x) / kotlin.math.abs(x) * 100)
            }
            Diff((ra ?: rb)!!.cat, (ra ?: rb)!!.name, va, vb, delta, va != vb)
        }
    }

    fun compareCsv(a: Snapshot, b: Snapshot, diffs: List<Diff>): String = buildString {
        append('﻿')
        append("Category,Item,${csvCell(a.label)},${csvCell(b.label)},Change,Different\r\n")
        diffs.forEach {
            append(listOf(it.cat, it.name, it.a, it.b, it.delta, if (it.different) "yes" else "").joinToString(",") { c -> csvCell(c) }).append("\r\n")
        }
    }

    // ---------- Files

    /** Writes into the app cache so it can be shared through ReportProvider. Returns a content:// URI. */
    fun shareable(ctx: Context, name: String, bytes: ByteArray): Uri {
        val dir = File(ctx.cacheDir, "reports").apply { mkdirs() }
        File(dir, name).writeBytes(bytes)
        return Uri.parse("content://${ctx.packageName}.reports/$name")
    }

    fun shareable(ctx: Context, name: String, bmp: Bitmap): Uri {
        val dir = File(ctx.cacheDir, "reports").apply { mkdirs() }
        File(dir, name).outputStream().use { bmp.compress(Bitmap.CompressFormat.PNG, 100, it) }
        return Uri.parse("content://${ctx.packageName}.reports/$name")
    }

    /** Saves to the public Downloads/HardwareScope (or Pictures/HardwareScope) folder. Returns a human-readable location. */
    @Suppress("DEPRECATION")
    fun savePublic(ctx: Context, name: String, mime: String, image: Boolean, write: (java.io.OutputStream) -> Unit): String {
        if (sdk(29)) {
            val cv = ContentValues().apply {
                put(MediaStore.MediaColumns.DISPLAY_NAME, name)
                put(MediaStore.MediaColumns.MIME_TYPE, mime)
                put(MediaStore.MediaColumns.RELATIVE_PATH, (if (image) Environment.DIRECTORY_PICTURES else Environment.DIRECTORY_DOWNLOADS) + "/HardwareScope")
            }
            val coll = if (image) MediaStore.Images.Media.EXTERNAL_CONTENT_URI else MediaStore.Downloads.EXTERNAL_CONTENT_URI
            val uri = ctx.contentResolver.insert(coll, cv) ?: throw IllegalStateException("Could not create file")
            ctx.contentResolver.openOutputStream(uri)!!.use(write)
            return (if (image) "Pictures" else "Download") + "/HardwareScope/$name"
        }
        // Android 9 and older: public folder if storage permission granted, else the app's own folder.
        val pub = Environment.getExternalStoragePublicDirectory(if (image) Environment.DIRECTORY_PICTURES else Environment.DIRECTORY_DOWNLOADS)
        var dir = File(pub, "HardwareScope")
        if (!(dir.exists() || dir.mkdirs()) || !dir.canWrite()) {
            dir = ctx.getExternalFilesDir(if (image) Environment.DIRECTORY_PICTURES else Environment.DIRECTORY_DOWNLOADS) ?: ctx.filesDir
        }
        val file = File(dir, name)
        file.outputStream().use(write)
        MediaScannerConnection.scanFile(ctx, arrayOf(file.absolutePath), arrayOf(mime), null)
        return file.absolutePath
    }

    /** Renders a view (including the off-screen part of a scrolling list) into a bitmap. */
    fun capture(v: View, background: Int, maxHeight: Int = 14000): Bitmap {
        val w = v.width.coerceAtLeast(1)
        val h = v.height.coerceAtLeast(1)
        val scale = if (h > maxHeight) maxHeight.toFloat() / h else 1f
        val bmp = Bitmap.createBitmap((w * scale).toInt().coerceAtLeast(1), (h * scale).toInt().coerceAtLeast(1), Bitmap.Config.ARGB_8888)
        val c = Canvas(bmp)
        c.drawColor(background)
        c.scale(scale, scale)
        v.draw(c)
        return bmp
    }
}
